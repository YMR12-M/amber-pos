/**
 * رقم طلب موحّد في كل الشاشات والفواتير: 42 → "#000042"
 *
 * الأرقام مصفوفة لستة خانات عشان الأعمدة تفضل متعامدة، والرقم اللي
 * على الشاشة يبقى هو هو اللي على الفاتورة — فالبحث في المرتجعات
 * بيدوّر على نص واحد مش نصين.
 *
 * الرقم متغلّف بـ LRI…PDI (U+2066/U+2069): من غيرهم علامة `#`
 * محايدة، فبتتزحلق لناحية الرقم التانية جوّه جملة عربية وتبقى
 * "000042#". الحرفين دول عرضهم صفر — مالهمش أي أثر على التخطيط.
 */
export function orderNo(id: number | string): string {
  // نفس تغليف `ltr()` اللي في lib/format — مكتوب هنا صراحةً عشان
  // الملف ده يفضل من غير imports: `scripts/brand-assets.mjs` بيقراه
  // بـ Node مباشرة، والـ resolver بتاعه مش بيقبل مسار من غير امتداد.
  return `\u2066#${String(id).padStart(6, "0")}\u2069`;
}
